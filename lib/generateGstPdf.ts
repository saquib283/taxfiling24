import { PDFDocument, rgb, StandardFonts, PDFPage, PDFFont } from "pdf-lib";

// ── Color Palette ──────────────────────────────────────────────────
const C = {
  primary: rgb(0.29, 0.33, 0.55),
  accent: rgb(0.35, 0.45, 0.92),
  dark: rgb(0.08, 0.09, 0.16),
  text: rgb(0.15, 0.16, 0.22),
  muted: rgb(0.45, 0.47, 0.55),
  light: rgb(0.65, 0.67, 0.72),
  white: rgb(1, 1, 1),
  bgLight: rgb(0.96, 0.965, 0.98),
  bgAccent: rgb(0.93, 0.94, 0.98),
  border: rgb(0.85, 0.86, 0.9),
  success: rgb(0.13, 0.58, 0.34),
  danger: rgb(0.78, 0.17, 0.22),
  amber: rgb(0.72, 0.58, 0.18),
  headerBg: rgb(0.07, 0.08, 0.14),
  stripeBg: rgb(0.97, 0.975, 0.99),
};

const PW = 595.28;
const PH = 841.89;
const ML = 48;
const MR = 48;
const CW = PW - ML - MR;

interface GstItem {
  name: string;
  unitPrice: number;
  quantity: number;
  gstRate: number;
  cessRate: number;
  discount: number;
  basePrice: number;
  gst: number;
  cess: number;
  total: number;
  discountVal: number;
}

export interface GstReportData {
  calcMode: string;
  placeOfSupply: string;
  taxScheme: string;
  isRcm: boolean;
  showMarginMode: boolean;
  margin: number;
  inputPurchases: number;
  inputGstRate: number;
  items: GstItem[];
  subTotal: number;
  totalGst: number;
  totalCess: number;
  totalDiscount: number;
  grandTotal: number;
  cgst: number;
  sgst: number;
  igst: number;
  itcAmount: number;
  netGstPayable: number;
  compositionTax: number;
  compositionRate: number;
}

function fmt(val: number): string {
  const f = new Intl.NumberFormat("en-IN", { maximumFractionDigits: 0 }).format(Math.round(val));
  return `Rs. ${f}`;
}

function fmtDec(val: number): string {
  const f = new Intl.NumberFormat("en-IN", { maximumFractionDigits: 2, minimumFractionDigits: 2 }).format(val);
  return `Rs. ${f}`;
}

// ── Draw helpers ───────────────────────────────────────────────────
function drawLine(p: PDFPage, y: number, color = C.border, t = 0.5) {
  p.drawLine({ start: { x: ML, y }, end: { x: PW - MR, y }, thickness: t, color });
}
function drawRect(p: PDFPage, x: number, y: number, w: number, h: number, c: ReturnType<typeof rgb>) {
  p.drawRectangle({ x, y, width: w, height: h, color: c });
}
function textRight(p: PDFPage, t: string, y: number, f: PDFFont, s: number, c: ReturnType<typeof rgb>) {
  const tw = f.widthOfTextAtSize(t, s);
  p.drawText(t, { x: PW - MR - tw, y, size: s, font: f, color: c });
}

function sectionHeader(p: PDFPage, title: string, y: number, fb: PDFFont): number {
  drawRect(p, ML, y - 2, 3, 14, C.accent);
  p.drawText(title.toUpperCase(), { x: ML + 12, y, size: 8.5, font: fb, color: C.primary });
  return y - 24;
}

function kvRow(p: PDFPage, label: string, value: string, y: number, fr: PDFFont, fb: PDFFont, striped = false): number {
  if (striped) drawRect(p, ML, y - 4, CW, 18, C.stripeBg);
  p.drawText(label, { x: ML + 8, y: y + 2, size: 8, font: fr, color: C.text });
  const tw = fb.widthOfTextAtSize(value, 8);
  p.drawText(value, { x: PW - MR - 8 - tw, y: y + 2, size: 8, font: fb, color: C.text });
  return y - 18;
}

// ══════════════════════════════════════════════════════════════════════
export async function generateGstReportPdf(data: GstReportData): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const fr = await doc.embedFont(StandardFonts.Helvetica);
  const fb = await doc.embedFont(StandardFonts.HelveticaBold);
  const fi = await doc.embedFont(StandardFonts.HelveticaOblique);

  let page = doc.addPage([PW, PH]);
  let y = PH;

  const addPageIfNeeded = (needed: number) => {
    if (y - needed < 60) {
      // Footer on current page
      drawRect(page, 0, 0, PW, 28, C.headerBg);
      page.drawText("Generated by TaxFiling24", { x: ML, y: 10, size: 7, font: fr, color: rgb(0.5, 0.55, 0.7) });
      const pg = `Page ${doc.getPageCount()}`;
      const pgw = fr.widthOfTextAtSize(pg, 6.5);
      page.drawText(pg, { x: (PW - pgw) / 2, y: 10, size: 6.5, font: fr, color: rgb(0.4, 0.45, 0.6) });

      page = doc.addPage([PW, PH]);
      y = PH - 30;
    }
  };

  // ═══════════════════════════════════════════════════════════════════
  // HEADER
  // ═══════════════════════════════════════════════════════════════════
  const hH = 88;
  drawRect(page, 0, PH - hH, PW, hH, C.headerBg);
  drawRect(page, 0, PH - hH, PW, 3, C.accent);

  page.drawText("TaxFiling24", { x: ML, y: PH - 36, size: 18, font: fb, color: C.white });
  page.drawText("GST Invoice Computation Report", { x: ML, y: PH - 54, size: 10, font: fr, color: rgb(0.65, 0.7, 0.85) });

  const dateText = new Date().toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" });
  let tw = fb.widthOfTextAtSize("Tax Invoice", 12);
  page.drawText("Tax Invoice", { x: PW - MR - tw, y: PH - 34, size: 12, font: fb, color: C.white });
  tw = fr.widthOfTextAtSize(dateText, 8);
  page.drawText(dateText, { x: PW - MR - tw, y: PH - 50, size: 8, font: fr, color: rgb(0.55, 0.6, 0.75) });

  y = PH - hH - 18;

  // ═══════════════════════════════════════════════════════════════════
  // CONFIGURATION STRIP
  // ═══════════════════════════════════════════════════════════════════
  drawRect(page, ML, y - 12, CW, 28, C.bgLight);
  drawLine(page, y - 12, C.border, 0.5);

  const configs = [
    `Mode: ${data.calcMode === "exclusive" ? "GST Exclusive" : "GST Inclusive"}`,
    `Supply: ${data.placeOfSupply === "intra" ? "Intra-State" : "Inter-State"}`,
    `Scheme: ${data.taxScheme === "regular" ? "Regular" : "Composition"}`,
    data.isRcm ? "RCM: Yes" : "",
  ].filter(Boolean);

  let cx = ML + 10;
  configs.forEach((item) => {
    page.drawText(item, { x: cx, y: y - 3, size: 7, font: fb, color: C.text });
    cx += fb.widthOfTextAtSize(item, 7) + 20;
  });
  y -= 42;

  // ═══════════════════════════════════════════════════════════════════
  // SECTION 1: LINE ITEMS TABLE
  // ═══════════════════════════════════════════════════════════════════
  y = sectionHeader(page, "Invoice Line Items", y, fb);

  // Table header
  const cols = [ML + 8, ML + 170, ML + 220, ML + 275, ML + 335, ML + 395, PW - MR - 8];
  const headers = ["Description", "Unit Price", "Qty", "Disc %", "GST %", "Tax Amt", "Line Total"];
  drawRect(page, ML, y - 4, CW, 20, C.headerBg);
  headers.forEach((h, i) => {
    const xPos = i === headers.length - 1
      ? cols[i] - fb.widthOfTextAtSize(h, 7)
      : cols[i];
    page.drawText(h, { x: xPos, y: y + 2, size: 7, font: fb, color: C.white });
  });
  y -= 22;

  // Data rows
  data.items.forEach((item, idx) => {
    addPageIfNeeded(20);
    if (idx % 2 === 1) drawRect(page, ML, y - 4, CW, 18, C.stripeBg);

    const name = item.name.length > 22 ? item.name.substring(0, 22) + "..." : item.name;
    page.drawText(name, { x: cols[0], y: y + 2, size: 7.5, font: fr, color: C.text });
    page.drawText(fmt(item.unitPrice), { x: cols[1], y: y + 2, size: 7.5, font: fr, color: C.text });
    page.drawText(String(item.quantity), { x: cols[2], y: y + 2, size: 7.5, font: fr, color: C.text });
    page.drawText(`${item.discount}%`, { x: cols[3], y: y + 2, size: 7.5, font: fr, color: C.text });
    page.drawText(`${item.gstRate}%`, { x: cols[4], y: y + 2, size: 7.5, font: fr, color: C.text });
    page.drawText(fmtDec(item.gst + item.cess), { x: cols[5], y: y + 2, size: 7.5, font: fb, color: C.text });

    const totalStr = fmtDec(item.total);
    const totalW = fb.widthOfTextAtSize(totalStr, 7.5);
    page.drawText(totalStr, { x: PW - MR - 8 - totalW, y: y + 2, size: 7.5, font: fb, color: C.text });
    y -= 18;
  });

  // Subtotal bar
  addPageIfNeeded(26);
  drawRect(page, ML, y - 4, CW, 22, C.bgAccent);
  page.drawText(`Subtotal (${data.items.length} items)`, { x: ML + 8, y: y + 3, size: 9, font: fb, color: C.primary });
  const stStr = fmt(data.subTotal);
  tw = fb.widthOfTextAtSize(stStr, 10);
  page.drawText(stStr, { x: PW - MR - 8 - tw, y: y + 2, size: 10, font: fb, color: C.primary });
  y -= 32;

  // ═══════════════════════════════════════════════════════════════════
  // SECTION 2: TAX BREAKDOWN
  // ═══════════════════════════════════════════════════════════════════
  addPageIfNeeded(120);
  y = sectionHeader(page, "Tax Computation Breakdown", y, fb);

  y = kvRow(page, "Taxable Value (Base Amount)", fmt(data.subTotal), y, fr, fb);

  if (data.totalDiscount > 0) {
    y = kvRow(page, "Less: Total Discounts Applied", `(-) ${fmt(data.totalDiscount)}`, y, fr, fb, true);
  }

  if (data.placeOfSupply === "intra") {
    y = kvRow(page, "Central GST (CGST) — 50%", fmtDec(data.cgst), y, fr, fb);
    y = kvRow(page, "State GST (SGST/UTGST) — 50%", fmtDec(data.sgst), y, fr, fb, true);
  } else {
    y = kvRow(page, "Integrated GST (IGST) — 100%", fmtDec(data.igst), y, fr, fb);
  }

  if (data.totalCess > 0) {
    y = kvRow(page, "Compensation Cess", fmtDec(data.totalCess), y, fr, fb, true);
  }

  y = kvRow(page, "Total GST Amount", fmt(data.totalGst), y, fr, fb);

  // Grand total bar
  y -= 2;
  drawRect(page, ML, y - 4, CW, 22, C.bgAccent);
  page.drawText("Grand Total (Taxable + Tax + Cess)", { x: ML + 8, y: y + 3, size: 9, font: fb, color: C.primary });
  const gtStr = fmt(data.grandTotal);
  tw = fb.widthOfTextAtSize(gtStr, 10);
  page.drawText(gtStr, { x: PW - MR - 8 - tw, y: y + 2, size: 10, font: fb, color: C.primary });
  y -= 32;

  // ═══════════════════════════════════════════════════════════════════
  // SECTION 3: ITC & NET PAYABLE
  // ═══════════════════════════════════════════════════════════════════
  addPageIfNeeded(100);
  y = sectionHeader(page, "Input Tax Credit & Net GST Liability", y, fb);

  if (data.itcAmount > 0) {
    y = kvRow(page, "Total Purchases (for ITC)", fmt(data.inputPurchases), y, fr, fb);
    y = kvRow(page, `Input GST Rate Applied (${data.inputGstRate}%)`, fmtDec(data.itcAmount), y, fr, fb, true);
    y = kvRow(page, "Eligible ITC Offset", `(-) ${fmt(data.itcAmount)}`, y, fr, fb);
  } else {
    y = kvRow(page, "Input Tax Credit (ITC)", "No ITC claimed", y, fr, fb);
  }

  if (data.isRcm) {
    y = kvRow(page, "Reverse Charge Mechanism (RCM)", "Applicable — Tax paid by recipient", y, fr, fb, true);
  }

  if (data.taxScheme === "composition") {
    y = kvRow(page, `Composition Scheme Rate (${data.compositionRate}%)`, fmtDec(data.compositionTax), y, fr, fb, true);
  }

  // Net payable highlight
  y -= 4;
  const netPayable = data.taxScheme === "composition" ? data.compositionTax : (data.isRcm ? 0 : data.netGstPayable);
  const npH = 34;
  drawRect(page, ML, y - npH + 16, CW, npH, C.primary);
  const npLabel = `Net GST Payable (Cash Liability): ${fmt(netPayable)}`;
  const npW = fb.widthOfTextAtSize(npLabel, 11);
  page.drawText(npLabel, { x: (PW - npW) / 2, y: y - 4, size: 11, font: fb, color: C.white });
  const npSub = data.taxScheme === "composition" ? "Under Composition Scheme" : (data.itcAmount > 0 ? "After ITC Offset" : "Standard Liability");
  const npSubW = fr.widthOfTextAtSize(npSub, 7);
  page.drawText(npSub, { x: (PW - npSubW) / 2, y: y - 16, size: 7, font: fr, color: rgb(0.78, 0.82, 0.95) });
  y -= npH + 14;

  // ═══════════════════════════════════════════════════════════════════
  // SECTION 4: MARGIN ANALYSIS (if enabled)
  // ═══════════════════════════════════════════════════════════════════
  if (data.showMarginMode) {
    addPageIfNeeded(80);
    y = sectionHeader(page, "Margin / Profit Analysis", y, fb);
    y = kvRow(page, "Expected Margin Percentage", `${data.margin}%`, y, fr, fb);
    y = kvRow(page, "Estimated Margin Profit", fmt(data.subTotal * (data.margin / 100)), y, fr, fb, true);
    y = kvRow(page, "Revenue After Tax & Margin", fmt(data.grandTotal), y, fr, fb);
    y -= 10;
  }

  // ═══════════════════════════════════════════════════════════════════
  // FOOTER
  // ═══════════════════════════════════════════════════════════════════
  addPageIfNeeded(60);
  drawLine(page, y, C.border, 0.5);
  y -= 14;
  page.drawText("Disclaimer:", { x: ML, y, size: 6.5, font: fb, color: C.muted });
  y -= 11;
  page.drawText(
    "This is a computer-generated GST computation estimate for informational purposes only. This does not constitute a valid tax invoice.",
    { x: ML, y, size: 6, font: fi, color: C.light }
  );
  y -= 9;
  page.drawText(
    "Please consult a qualified GST practitioner or Chartered Accountant for filing and compliance advisory.",
    { x: ML, y, size: 6, font: fi, color: C.light }
  );
  y -= 18;

  drawRect(page, 0, 0, PW, 28, C.headerBg);
  page.drawText("Generated by TaxFiling24", { x: ML, y: 10, size: 7, font: fr, color: rgb(0.5, 0.55, 0.7) });
  const urlText = "www.taxfiling24.com";
  tw = fr.widthOfTextAtSize(urlText, 7);
  page.drawText(urlText, { x: PW - MR - tw, y: 10, size: 7, font: fr, color: rgb(0.5, 0.55, 0.7) });
  const pgText = `Page ${doc.getPageCount()} of ${doc.getPageCount()}`;
  const pgW = fr.widthOfTextAtSize(pgText, 6.5);
  page.drawText(pgText, { x: (PW - pgW) / 2, y: 10, size: 6.5, font: fr, color: rgb(0.4, 0.45, 0.6) });

  return await doc.save();
}
